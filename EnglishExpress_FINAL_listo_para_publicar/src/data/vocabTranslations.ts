/**
 * Traduce un término de vocabulario al español. Si no existe en el
 * diccionario (caso raro), regresa el término tal cual, para nunca
 * romper la pantalla ni mostrar 'undefined'.
 */
export function translateVocabTerm(term: string): string {
  const key = term.trim().toLowerCase();
  return VOCAB_TRANSLATIONS[key] || term;
}

/**
 * Separa un texto de vocabFocus en términos individuales por coma,
 * IGNORANDO las comas que están dentro de paréntesis (por ejemplo:
 * 'Colors (black, white, blue)' se mantiene como UN solo término,
 * en vez de partirse a la mitad por las comas internas).
 */
export function splitVocabFocus(text: string): string[] {
  const result: string[] = [];
  let depth = 0;
  let current = '';
  for (const ch of text) {
    if (ch === '(') depth++;
    if (ch === ')') depth = Math.max(0, depth - 1);
    if (ch === ',' && depth === 0) {
      result.push(current.trim());
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) result.push(current.trim());
  return result.filter(Boolean);
}